enemy::enemy(int startX, int startY) {
  x = startX;
  y = startY;
}

void enemy::move(int dx, int dy, int screenWidth, int screenHeight) {
  int rx,ry;
  rx=random(0,124);
 
  y +=dy;
  x+=dx;

  // Limitează mișcarea în ecran
  if (x < 0) x = 124;
  if (y < 0) y = 64;
  if (x > screenWidth - 8) x = 0;
  if (y > screenHeight - 8){ y = 0;x=rx;}
}

void enemy::draw(Adafruit_SSD1306 &display) {
  display.drawBitmap(x, y, character_bitmap, 20, 20, WHITE);
}